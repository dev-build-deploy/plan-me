import fs from "fs";
import path from "path";

import yaml from "js-yaml";

import { COMMANDS } from "../src/commands";
import { resolveConfig } from "../src/config";
import {
  checkTemplates,
  fileState,
  parseFormAnswers,
  sectionsFor,
  templateFileName,
  TYPE_SPECS,
  writeTemplates,
} from "../src/templates";

import { repo } from "./repo";

/** A notes app: three components, one board known by number. */
const RAW = {
  repository: "octo-org/notes",
  boards: { api: "API", web: "Web", mobile: { title: "Mobile app", number: 7 } },
  defaultComponent: "web",
  fields: { role: { options: ["lead", "backend", "frontend", "user"] } },
};
const CONFIG = resolveConfig(RAW);
const ORG_TYPES = ["Feature", "Bug", "Task"];
const DIR = ".github/ISSUE_TEMPLATE";

type Element = {
  type: string;
  id?: string;
  attributes: { label?: string; options?: string[]; default?: number; value?: string };
  validations?: { required?: boolean };
};
type Form = {
  name: string;
  description: string;
  type?: string;
  labels?: string[];
  projects?: string[];
  body: Element[];
};

const read = (root: string, file: string): string => fs.readFileSync(path.join(root, file), "utf8");
const form = (root: string, file: string): Form => yaml.load(read(root, `${DIR}/${file}`)) as Form;

describe("writing the forms", () => {
  test("one valid form per type and config.yml; a second run is up to date", () => {
    const root = repo();
    const out = writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES, year: "2026" });
    expect(out.actions).toEqual(
      ["feature", "bug", "task", "design", "decision", "epic", "config"].map(n => `write ${DIR}/${n}.yml`)
    );
    expect(out.skipped).toEqual([]);
    for (const name of fs.readdirSync(path.join(root, DIR))) {
      const text = read(root, `${DIR}/${name}`);
      expect(text).toMatch(/^# Generated by plan-me/);
      expect(fileState(text)).toBe("generated");
      if (name === "config.yml") continue;
      const f = form(root, name);
      expect(Object.keys(f).slice(0, 3)).toEqual(["name", "description", f.type ? "type" : "labels"]);
      const ids = f.body.filter(e => e.id).map(e => e.id);
      expect(new Set(ids).size).toBe(ids.length);
      for (const e of f.body.filter(el => el.type === "dropdown")) {
        expect(e.attributes.options).not.toContain("None");
        expect(new Set(e.attributes.options).size).toBe(e.attributes.options?.length);
      }
    }
    expect(writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES })).toEqual({ actions: [], skipped: [] });
    expect(checkTemplates(root, CONFIG, { issueTypes: ORG_TYPES })).toEqual([]);
  });

  test("the bug form: its sections, the issue type, the component and field dropdowns", () => {
    const root = repo();
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    const bug = form(root, "bug.yml");
    expect(bug).toMatchObject({ name: "Bug", description: "Something does not work as it should", type: "Bug" });
    expect(bug.labels).toBeUndefined();
    expect(bug.projects).toBeUndefined(); // three boards: the Action puts the issue on the chosen one
    expect(bug.body.map(e => e.attributes.label)).toEqual([
      "Context",
      "Steps to reproduce",
      "Observed behavior",
      "Expected behavior",
      "Additional context",
      "Component",
      "Priority",
      "Role",
      "Effort",
    ]);
    const byLabel = (label: string): Element | undefined => bug.body.find(e => e.attributes.label === label);
    expect(byLabel("Steps to reproduce")?.validations?.required).toBe(true);
    for (const label of ["Context", "Observed behavior", "Expected behavior", "Additional context"]) {
      expect(byLabel(label)?.validations?.required).toBe(true);
    }
    expect(byLabel("Component")?.attributes).toMatchObject({ options: ["api", "web", "mobile"], default: 1 });
    expect(byLabel("Priority")?.attributes).toMatchObject({ options: ["Urgent", "High", "Medium", "Low"], default: 2 });
    expect(byLabel("Role")?.attributes.options).toEqual(["lead", "backend", "frontend", "user"]);
    expect(byLabel("Effort")?.attributes).toMatchObject({ options: ["High", "Medium", "Low"] });
    expect(byLabel("Effort")?.attributes.default).toBeUndefined();
  });

  test("types the organization lacks use the type label; the decision form explains ask and decide", () => {
    const root = repo();
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    const decision = form(root, "decision.yml");
    expect(decision.type).toBeUndefined();
    expect(decision.labels).toEqual(["type:decision"]);
    expect(decision.body[0]).toMatchObject({ type: "markdown" });
    expect(decision.body[0].attributes.value).toContain("plan-me decide");
    expect(decision.body.map(e => e.attributes.label)).toContain("Who decides");
    expect(decision.body.find(e => e.attributes.label === "Who decides")?.validations?.required).toBe(true);
    const labels = (name: string, n: number): (string | undefined)[] =>
      form(root, name)
        .body.map(e => e.attributes.label)
        .slice(0, n);
    expect(labels("epic.yml", 6)).toEqual(["Why", "Context", "What", "Outcome", "Child items", "Design docs"]);
    expect(labels("feature.yml", 5)).toEqual([
      "Context",
      "Problem",
      "Expected value",
      "Acceptance criteria",
      "Design docs",
    ]);
    expect(labels("task.yml", 4)).toEqual(["Why", "Context", "What", "Done when"]);
    expect(labels("design.yml", 6)).toEqual(["Why", "Context", "What", "Constraints", "Options", "Design docs"]);
  });

  test("one board with a number: projects; no boards: no component dropdown; free-text role: an input", () => {
    const one = resolveConfig({ repository: "octo-org/notes", boards: { web: { title: "Web", number: 3 } } });
    const root = repo();
    writeTemplates(root, one, { issueTypes: [] });
    const task = form(root, "task.yml");
    expect(task.projects).toEqual(["octo-org/3"]);
    expect(task.labels).toEqual(["type:task"]);
    expect(task.body.map(e => e.attributes.label)).not.toContain("Component");
    expect(task.body.find(e => e.attributes.label === "Role")?.type).toBe("input");
  });

  test("a form generated before the sections changed is reported stale", () => {
    const root = repo();
    const task = TYPE_SPECS.task;
    TYPE_SPECS.task = { ...task, sections: [{ label: "What to do", required: true }] };
    try {
      writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    } finally {
      TYPE_SPECS.task = task;
    }
    expect(checkTemplates(root, CONFIG, { issueTypes: ORG_TYPES })).toEqual([
      `${DIR}/task.yml: stale (the configuration changed); run \`plan-me templates\``,
    ]);
  });

  test("a custom type gets the core sections; the chooser follows the templates settings", () => {
    const config = resolveConfig({
      ...RAW,
      types: ["Bug", "Spike"],
      templates: {
        blankIssues: true,
        contactLinks: [{ name: "Questions", url: "https://example.com/forum", about: "Ask the community" }],
      },
    });
    const root = repo();
    writeTemplates(root, config, { issueTypes: [] });
    expect(fs.readdirSync(path.join(root, DIR)).sort()).toEqual(["bug.yml", "config.yml", "spike.yml"]);
    expect(form(root, "spike.yml")).toMatchObject({ name: "Spike", description: "A spike", labels: ["type:spike"] });
    expect(sectionsFor("Spike").map(s => s.label)).toEqual(["Why", "Context", "What"]);
    expect(yaml.load(read(root, `${DIR}/config.yml`))).toEqual({
      blank_issues_enabled: true,
      contact_links: [{ name: "Questions", url: "https://example.com/forum", about: "Ask the community" }],
    });
    expect(templateFileName("Config")).toBe("type-config.yml");
  });

  test('"templates": false writes and checks nothing', () => {
    const root = repo();
    const off = resolveConfig({ ...RAW, templates: false });
    expect(writeTemplates(root, off)).toEqual({ actions: [], skipped: [] });
    expect(fs.existsSync(path.join(root, DIR))).toBe(false);
    expect(checkTemplates(root, off)).toEqual([]);
    expect(CONFIG.templates).toEqual({ enabled: true, blankIssues: false, contactLinks: [] });
  });

  test("dry run prints what it would write and writes nothing", () => {
    const root = repo();
    const out = writeTemplates(root, CONFIG, { dryRun: true });
    expect(out.actions[0]).toBe(`would write ${DIR}/feature.yml`);
    expect(fs.existsSync(path.join(root, DIR))).toBe(false);
  });
});

describe("hand edits, configuration changes and the check", () => {
  test("a form edited by hand is left alone (and passes the check) unless --force", () => {
    const root = repo();
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    const file = path.join(root, DIR, "bug.yml");
    const edited = fs.readFileSync(file, "utf8").replace("Steps to reproduce", "How to reproduce");
    fs.writeFileSync(file, edited);
    expect(fileState(edited)).toBe("edited");
    const changed = resolveConfig({ ...RAW, boards: { ...RAW.boards, desktop: "Desktop" } });
    const out = writeTemplates(root, changed, { issueTypes: ORG_TYPES });
    expect(out.skipped).toEqual([`${DIR}/bug.yml edited by hand: left alone (--force overwrites)`]);
    expect(out.actions).toContain(`update ${DIR}/feature.yml`);
    expect(out.actions).not.toContain(`update ${DIR}/config.yml`); // the chooser doesn't depend on the boards
    expect(fs.readFileSync(file, "utf8")).toBe(edited);
    expect(checkTemplates(root, changed, { issueTypes: ORG_TYPES })).toEqual([]);
    const forced = writeTemplates(root, changed, { issueTypes: ORG_TYPES, force: true });
    expect(forced).toEqual({ actions: [`update ${DIR}/bug.yml`], skipped: [] });
    expect(form(root, "bug.yml").body.find(e => e.id === "component")?.attributes.options).toContain("desktop");
  });

  test("a template plan-me didn't write is left alone; a folder without plan-me's forms passes the check", () => {
    const root = repo({ [`${DIR}/bug.yml`]: "name: Bug\ndescription: ours\nbody: []\n" });
    expect(checkTemplates(root, CONFIG)).toEqual([]);
    const out = writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    expect(out.skipped).toEqual([`${DIR}/bug.yml not written by plan-me: left alone (--force overwrites)`]);
    expect(read(root, `${DIR}/bug.yml`)).toContain("description: ours");
    expect(checkTemplates(repo(), CONFIG)).toEqual([]);
  });

  test("the check: a stale form, a missing one, one for a type no longer configured; templates fixes them", () => {
    const root = repo();
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    fs.unlinkSync(path.join(root, DIR, "task.yml"));
    const types = ["Feature", "Bug", "Task", "Design", "Decision"];
    const changed = resolveConfig({ ...RAW, types });
    const p3 = resolveConfig({ ...RAW, types, fields: { ...RAW.fields, priority: { default: "low" } } });
    const problems = checkTemplates(root, p3, { issueTypes: ORG_TYPES });
    expect(problems).toContain(`${DIR}/task.yml: missing; run \`plan-me templates\``);
    expect(problems).toContain(`${DIR}/bug.yml: stale (the configuration changed); run \`plan-me templates\``);
    expect(problems).toContain(`${DIR}/epic.yml: its type is no longer configured; run \`plan-me templates\``);
    const out = writeTemplates(root, changed, { issueTypes: ORG_TYPES });
    expect(out.actions).toEqual([`write ${DIR}/task.yml`, `remove ${DIR}/epic.yml`]);
    expect(checkTemplates(root, changed, { issueTypes: ORG_TYPES })).toEqual([]);
  });

  test("without the organization's issue types (no token) each form keeps its kind; new forms use the label", () => {
    const root = repo();
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES });
    expect(checkTemplates(root, CONFIG)).toEqual([]);
    expect(writeTemplates(root, CONFIG)).toEqual({ actions: [], skipped: [] });
    expect(form(root, "bug.yml").type).toBe("Bug");
    const fresh = repo();
    writeTemplates(fresh, CONFIG);
    expect(form(fresh, "bug.yml").labels).toEqual(["type:bug"]);
    // the organization gained the type: the check (with a token) asks for a rewrite
    expect(checkTemplates(fresh, CONFIG, { issueTypes: ORG_TYPES })).toContain(
      `${DIR}/bug.yml: stale (the configuration changed); run \`plan-me templates\``
    );
  });
});

describe("licence headers (.reuse-me.json)", () => {
  /** Built from parts so no line of this test starts with an SPDX tag (REUSE tools read those). */
  const TAG = "SPDX-";
  const REUSE = JSON.stringify({ rules: [{ paths: [".github/**"], holder: "Octo Org", license: "CC0-1.0" }] });

  test("each file gets the matching rule's header as YAML comments; an existing file keeps its year", () => {
    const root = repo({ ".reuse-me.json": REUSE });
    writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES, year: "2025" });
    const bug = read(root, `${DIR}/bug.yml`);
    expect(bug).toMatch(
      new RegExp(`^# ${TAG}FileCopyrightText: 2025 Octo Org\n# ${TAG}License-Identifier: CC0-1.0\n\n# Generated`)
    );
    expect(yaml.load(bug)).toMatchObject({ name: "Bug" });
    expect(writeTemplates(root, CONFIG, { issueTypes: ORG_TYPES, year: "2027" })).toEqual({ actions: [], skipped: [] });
    expect(checkTemplates(root, CONFIG, { issueTypes: ORG_TYPES, year: "2027" })).toEqual([]);
    const without = repo();
    writeTemplates(without, CONFIG);
    expect(read(without, `${DIR}/bug.yml`)).not.toContain(TAG);
  });
});

describe("parseFormAnswers", () => {
  test("the answers by heading; empty answers left out", () => {
    const body = [
      "### Problem",
      "",
      "Share a note by link.",
      "",
      "### Acceptance criteria",
      "",
      "- [ ] a link opens the note",
      "- [ ] read only",
      "",
      "### Design docs",
      "",
      "_No response_",
      "",
      "### Component",
      "",
      "api",
      "",
      "### Effort",
      "",
      "None",
    ].join("\r\n");
    expect(parseFormAnswers(body)).toEqual({
      Problem: "Share a note by link.",
      "Acceptance criteria": "- [ ] a link opens the note\n- [ ] read only",
      Component: "api",
    });
    expect(parseFormAnswers("A blank issue.")).toEqual({});
  });
});

describe("the commands", () => {
  const noBacklog = (): never => {
    throw new Error("no token");
  };

  test("templates and templates_check work without a token", async () => {
    const root = repo();
    const ctx = { backlog: noBacklog, root, config: () => CONFIG };
    const first = await COMMANDS.templates.run(ctx, {});
    expect(first.text.split("\n")[0]).toBe(`write ${DIR}/feature.yml`);
    expect((await COMMANDS.templates.run(ctx, {})).text).toBe(`${DIR} up to date`);
    expect(await COMMANDS.templates_check.run(ctx, {})).toMatchObject({ text: `${DIR}: ok`, failed: false });
    fs.unlinkSync(path.join(root, DIR, "epic.yml"));
    const bad = await COMMANDS.templates_check.run(ctx, {});
    expect(bad.failed).toBe(true);
    expect(bad.text).toBe(`${DIR}/epic.yml: missing; run \`plan-me templates\``);
    const dry = await COMMANDS.templates.run(ctx, { dryRun: true });
    expect(dry.text).toBe(`would write ${DIR}/epic.yml`);
    expect(dry.json).toMatchObject({ dryRun: true });
  });
});
