function decision(over: Partial<Decision>): Decision {
  return {
    id: "a",
    date: "2026-11-01",
    by: "the user",
    status: "current",
    scope: [],
    summary: "Summary of a",
    title: "Title a",
    text: "The decision a.",
    ...over,
  };
}

/** The files of a set of decisions, as `{path: text}`. */
function files(...ds: Decision[]): Record<string, string> {
  return Object.fromEntries(ds.map(d => [`docs/decisions/${d.date}-${d.id}.md`, formatDecision(d)]));
}

const read = (root: string, file: string): string => fs.readFileSync(path.join(root, file), "utf8");

describe("decision files", () => {
  test("slugs", () => {
    expect(slugify("The paint budget is the printer's")).toBe("paint-budget-is-the-printers");
    // The cut never ends on a stop word, and a leading "the" goes (#25).
    expect(slugify("What has no future in the new release is removed")).toBe("what-has-no-future");
    expect(slugify("The report is built from the nightly data")).toBe("report-is-built");
    expect(slugify("Of and the")).toBe("of-and-the");
    expect(slugify("The")).toBe("the");
    expect(slugify("Één ruimte: São Paulo & co!")).toBe("een-ruimte-sao-paulo-co");
    expect(slugify("one two three four five six seven")).toBe("one-two-three-four-five-six");
    expect(slugify("!!!")).toBe("decision");
  });

  test("front matter: quoted values keep # and escapes", () => {
    const { data } = parseFrontMatter('---\nq: "#12"\ns: "say \\"hi\\" # not a comment"\nt: plain # comment\n---\n');
    expect(data).toEqual({ q: "#12", s: 'say "hi" # not a comment', t: "plain" });
  });

  test("format and parse round trip", () => {
    const d = decision({ number: "L99", scope: ["ui", "engine"], question: "#12", summary: 'A "quoted" #1 line' });
    const text = formatDecision(d);
    expect(text).toBe(
      [
        "---",
        "id: a",
        "number: L99",
        "date: 2026-11-01",
        'by: "the user"',
        "status: current",
        "superseded_by:",
        "scope: [ui, engine]",
        'summary: "A \\"quoted\\" #1 line"',
        'question: "#12"',
        "---",
        "",
        "# Title a",
        "",
        "The decision a.",
        "",
      ].join("\n")
    );
    expect(parseDecision("docs/decisions/2026-11-01-a.md", text)).toEqual({ decision: d, problems: [] });
  });
});

describe("index", () => {
  const ds = [
    decision({ id: "newest", date: "2026-11-02", summary: "The newest" }),
    decision({ id: "old", number: "9", date: "2026-10-01", status: "superseded", supersededBy: "newest" }),
    decision({ id: "changed", number: "L3", status: "amended", supersededBy: "newest", scope: ["ui", "map"] }),
    decision({ id: "b", number: "12", summary: "Twelve" }),
    decision({ id: "c", number: "102", summary: "Hundred and two" }),
  ];

  test("the format: header, current, amended, superseded; newest first, then the higher number", () => {
    expect(formatIndex(ds, DEFAULT_DECISIONS)).toBe(
      [
        "<!-- Generated by plan-me from docs/decisions/: do not edit by hand. Regenerate with `plan-me decisions index`. -->",
        "",
        "# Decisions",
        "",
        "One file per decision in [docs/decisions/](decisions/), named",
        "`<date>-<id>.md`. One line per decision here, in this format:",
        "",
        "`- <id> · <number or -> · <date> · <status> · <scope or -> · <summary>`",
        "",
        "`number` is only set for decisions imported from an old numbered list (decision 129, L99).",
        "",
        "## Current",
        "",
        "Valid: follow these.",
        "",
        "- newest · - · 2026-11-02 · current · - · The newest",
        "- c · 102 · 2026-11-01 · current · - · Hundred and two",
        "- b · 12 · 2026-11-01 · current · - · Twelve",
        "",
        "## Amended",
        "",
        "Still valid, but changed by a later decision: read the one named after `amended by` too.",
        "",
        "- changed · L3 · 2026-11-01 · amended by newest · ui, map · Summary of a",
        "",
        "## Superseded",
        "",
        "History only: never follow these; follow the decision named after `superseded by`.",
        "",
        "- old · 9 · 2026-10-01 · superseded by newest · - · Summary of a",
        "",
      ].join("\n")
    );
  });

  test("deterministic whatever the file order; empty sections say (none)", () => {
    expect(formatIndex([...ds].reverse(), DEFAULT_DECISIONS)).toBe(formatIndex(ds, DEFAULT_DECISIONS));
    expect(formatIndex([], DEFAULT_DECISIONS).match(/\(none\)/g)).toHaveLength(3);
  });

  test("writeIndex writes once, then reports unchanged", () => {
    const root = repo(files(...ds));
    expect(writeIndex(root)).toBe(true);
    expect(writeIndex(root)).toBe(false);
    expect(read(root, "docs/decisions.md")).toBe(formatIndex(ds, DEFAULT_DECISIONS));
    expect(checkDecisions(root)).toEqual([]);
  });

  test("writeIndex refuses invalid files", () => {
    const root = repo({ "docs/decisions/2026-11-01-a.md": "---\nid: a\n---\n" });
    expect(() => writeIndex(root)).toThrow(/by is missing/);
  });
});

describe("check", () => {
  /** A repository with the decisions and their up-to-date index. */
  function clean(...ds: Decision[]): string {
    const root = repo(files(...ds));
    writeIndex(root);
    return root;
  }

  test("no decisions folder: clean, whatever docs/decisions.md holds", () => {
    expect(checkDecisions(repo())).toEqual([]);
    expect(checkDecisions(repo({ "docs/decisions.md": "# A hand-written guide\n" }))).toEqual([]);
  });

  test("a decisions folder without an index", () => {
    const root = repo(files(decision({})));
    expect(checkDecisions(root)).toEqual(["docs/decisions.md: missing; run `plan-me decisions index`"]);
  });

  test("invalid front matter", () => {
    const root = repo({
      "docs/decisions/2026-11-01-bad.md":
        '---\nid: Bad Id\ndate: 1 Nov\nstatus: maybe\nsummary: ""\nnumber: decision-9\nquestion: "12"\n---\n\nno title\n',
    });
    expect(checkDecisions(root)).toEqual([
      'docs/decisions/2026-11-01-bad.md: id "Bad Id" must be a slug (a-z, 0-9, single dashes)',
      'docs/decisions/2026-11-01-bad.md: date "1 Nov" must be YYYY-MM-DD',
      "docs/decisions/2026-11-01-bad.md: by is missing",
      'docs/decisions/2026-11-01-bad.md: status "maybe" must be one of current, amended, superseded',
      "docs/decisions/2026-11-01-bad.md: summary must be one line",
      'docs/decisions/2026-11-01-bad.md: number "decision-9" must be the original label (129, L99)',
      'docs/decisions/2026-11-01-bad.md: question "12" must be an issue (#12)',
      "docs/decisions/2026-11-01-bad.md: the `# title` heading is missing",
      "docs/decisions.md: missing; run `plan-me decisions index`",
    ]);
  });

  test("status and superseded_by must agree; the file name follows date and id", () => {
    const root = repo({
      ...files(decision({ id: "x", status: "superseded" }), decision({ id: "y", supersededBy: "x" })),
      "docs/decisions/renamed.md": formatDecision(decision({ id: "z" })),
    });
    const problems = checkDecisions(root);
    expect(problems).toContain("docs/decisions/2026-11-01-x.md: a superseded decision needs superseded_by");
    expect(problems).toContain("docs/decisions/2026-11-01-y.md: a current decision can't have superseded_by");
    expect(problems).toContain("docs/decisions/renamed.md: the file must be named 2026-11-01-z.md");
  });

  test("colliding ids and numbers", () => {
    const root = repo({
      ...files(decision({ id: "same", number: "7" }), decision({ id: "other", number: "7" })),
      "docs/decisions/2026-10-01-same.md": formatDecision(decision({ id: "same", date: "2026-10-01" })),
    });
    const problems = checkDecisions(root);
    expect(problems).toContain('docs/decisions: id "same" is used by 2 decisions');
    expect(problems).toContain("docs/decisions: number 7 is used by 2 decisions");
  });

  test("superseded_by pointing nowhere", () => {
    const root = repo(files(decision({ id: "old", status: "superseded", supersededBy: "ghost" })));
    expect(checkDecisions(root)).toContain('docs/decisions/2026-11-01-old.md: superseded_by "ghost" is no decision');
  });

  test("a stale index (a new file) and a hand-edited one", () => {
    const root = clean(decision({ id: "a" }));
    expect(checkDecisions(root)).toEqual([]);
    fs.writeFileSync(
      path.join(root, "docs/decisions/2026-11-02-b.md"),
      formatDecision(decision({ id: "b", date: "2026-11-02" }))
    );
    expect(checkDecisions(root)).toEqual([
      'docs/decisions.md: stale or edited by hand (line 16: expected "- b · - · 2026-11-02 · current · - · Summary of a", found "- a · - · 2026-11-01 · current · - · Summary of a"); run `plan-me decisions index`',
    ]);
    writeIndex(root);
    fs.appendFileSync(path.join(root, "docs/decisions.md"), "- my own line\n");
    expect(checkDecisions(root)[0]).toMatch(
      /^docs\/decisions\.md: stale or edited by hand \(line 30: expected "", found "- my own line"\)/
    );
  });
});

describe("decide (recording)", () => {
  const input = { text: "We use files.", title: "Decisions are files", by: "the owner", date: "2026-11-01" };

  test("writes the file and the index; the same input again changes nothing", () => {
    const root = repo();
    const first = recordDecision(root, { ...input, scope: ["docs"] });
    expect(first.actions).toEqual([
      "wrote docs/decisions/2026-11-01-decisions-are-files.md",
      "wrote docs/decisions.md",
    ]);
    expect(read(root, first.path)).toContain("id: decisions-are-files\n");
    expect(read(root, "docs/decisions.md")).toContain(
      "- decisions-are-files · - · 2026-11-01 · current · docs · Decisions are files\n"
    );
    expect(recordDecision(root, { ...input, scope: ["docs"] })).toMatchObject({ changed: false, actions: [] });
    expect(checkDecisions(root)).toEqual([]);
  });

  test("an id taken by another decision is an error", () => {
    const root = repo();
    recordDecision(root, input);
    expect(() => recordDecision(root, { ...input, text: "Something else." })).toThrow(/exists .*pass another --id/);
    expect(recordDecision(root, { ...input, text: "Something else.", id: "files-two" }).changed).toBe(true);
  });

  test("--supersedes and --amends mark the older decisions", () => {
    const root = repo();
    recordDecision(root, { ...input, title: "Old way", date: "2026-10-01" });
    recordDecision(root, { ...input, title: "Other way", date: "2026-10-02" });
    const out = recordDecision(root, { ...input, supersedes: "old-way", amends: "other-way" });
    expect(out.actions).toEqual([
      "wrote docs/decisions/2026-11-01-decisions-are-files.md",
      "old-way superseded by decisions-are-files",
      "other-way amended by decisions-are-files",
      "wrote docs/decisions.md",
    ]);
    const index = read(root, "docs/decisions.md");
    expect(index).toContain("- old-way · - · 2026-10-01 · superseded by decisions-are-files · - · Old way");
    expect(index).toContain("- other-way · - · 2026-10-02 · amended by decisions-are-files · - · Other way");
    expect(checkDecisions(root)).toEqual([]);
    expect(() => recordDecision(root, { ...input, title: "New", supersedes: "nope" })).toThrow(
      'no decision with id "nope"'
    );
  });

  test("ask then decide: the question issue gets the answer", async () => {
    const { api, backlog } = setup();
    const root = repo();
    const ctx = { backlog: () => backlog, root };
    const { item } = await backlog.create({ title: "Which store?" });
    const asked = await COMMANDS.ask.run(ctx, { ref: item.number, question: "Files or a database?" });
    expect(asked.text).toBe(`#1 status open -> needs-decision; comment\n#1 [game medium needs-decision] Which store?`);
    expect(asked.warning).toBeUndefined();

    const recorded = await COMMANDS.decide.run(ctx, { ...input, question: "#1" });
    expect(recorded.text).toBe(
      [
        "wrote docs/decisions/2026-11-01-decisions-are-files.md",
        "wrote docs/decisions.md",
        "- decisions-are-files · - · 2026-11-01 · current · - · Decisions are files",
        "#1 comment; decision docs/decisions/2026-11-01-decisions-are-files.md; status needs-decision -> in-progress",
        "#1 [game medium in-progress] Which store?",
      ].join("\n")
    );
    expect(read(root, "docs/decisions/2026-11-01-decisions-are-files.md")).toContain('question: "#1"');
    expect(api.comments.get(1)?.[1]).toBe(
      "**Decided:** Decisions are files\n\nThe decision is `docs/decisions/2026-11-01-decisions-are-files.md`. " +
        "The pull request that adds this file closes this issue (`Closes #1` in its description)."
    );
    expect(api.issues.get(1)?.body).toContain("Decision: docs/decisions/2026-11-01-decisions-are-files.md");

    const again = await COMMANDS.decide.run(ctx, { ...input, question: 1 });
    expect(again.text).toBe(
      [
        "docs/decisions/2026-11-01-decisions-are-files.md unchanged",
        "- decisions-are-files · - · 2026-11-01 · current · - · Decisions are files",
        "#1 unchanged",
        "#1 [game medium in-progress] Which store?",
      ].join("\n")
    );
    await expect(COMMANDS.decide.run(ctx, { title: "No text" })).rejects.toThrow(/needs text, title and by/);
    await expect(COMMANDS.decide.run(ctx, {})).rejects.toThrow(/needs text, title and by/);
  });

  test("ask with a title opens a new question issue; asking again returns it", async () => {
    const { api, backlog } = setup();
    const ctx = { backlog: () => backlog, root: repo() };
    const first = await COMMANDS.ask.run(ctx, { ref: "Files or a database?", question: "Where do decisions live?" });
    expect(first.text).toBe(
      "#1 created #1; status - -> open; priority - -> medium; status open -> needs-decision\n" +
        "#1 [game medium needs-decision] Files or a database?"
    );
    expect(api.issues.get(1)?.body).toContain("Where do decisions live?");
    expect(api.issues.get(1)?.labels).toContain("type:decision"); // the fake's organization has no Decision type
    expect(api.issues.get(1)?.body).toContain("<!-- plan-me:id=ask-files-or-a-database -->");
    const again = await COMMANDS.ask.run(ctx, { ref: "Files or a database?", question: "Where do decisions live?" });
    expect(again.text).toBe("#1 unchanged\n#1 [game medium needs-decision] Files or a database?");
  });

  test("the old decide <ref> --question form still asks, with a deprecation warning naming ask", async () => {
    const { backlog } = setup();
    const ctx = { backlog: () => backlog, root: repo() };
    await backlog.create({ title: "Which store?" });
    const old = await COMMANDS.decide.run(ctx, { ref: 1, question: "Files or a database?" });
    expect(old.text).toBe(`#1 status open -> needs-decision; comment\n#1 [game medium needs-decision] Which store?`);
    expect(old.warning).toMatch(/deprecated.*plan-me ask <ref> "<question>"/);
  });

  test("recording needs no backlog without a question", async () => {
    const root = repo();
    const ctx = {
      backlog: () => {
        throw new Error("no backlog");
      },
      root,
    };
    const out = await COMMANDS.decide.run(ctx, input);
    expect(out.text).toContain("wrote docs/decisions.md");
    expect((await COMMANDS.decisions_check.run(ctx, {})).text).toBe("docs/decisions: ok");
    expect((await COMMANDS.decisions_index.run(ctx, {})).text).toBe("docs/decisions.md up to date");
    fs.writeFileSync(path.join(root, "docs/decisions.md"), "edited\n");
    const failed = await COMMANDS.decisions_check.run(ctx, {});
    expect(failed.failed).toBe(true);
    expect((await COMMANDS.decisions_index.run(ctx, {})).text).toBe("docs/decisions.md written");
    expect(readDecisions(root, DEFAULT_DECISIONS).decisions).toHaveLength(1);
  });
});

describe("licence headers (.reuse-me.json)", () => {
  /** Built from parts so no line of this test starts with an SPDX tag (REUSE tools read those). */
  const TAG = "SPDX-";
  const REUSE = JSON.stringify({
    rules: [
      { paths: ["games/**"], holder: "Someone Else", license: "LicenseRef-Proprietary" },
      {
        paths: ["docs/**"],
        holder: ["Kevin de Jong <monkaii@hotmail.com>", "2024 Other Holder"],
        license: "CC-BY-4.0",
      },
    ],
    defaults: { holder: "Default Holder" },
  });
  const input = { text: "We use files.", title: "Decisions are files", by: "the owner", date: "2025-03-04" };

  test("with .reuse-me.json: the first matching rule's holder and licence, the decision's year", () => {
    const root = repo({ ".reuse-me.json": REUSE });
    const { path: file } = recordDecision(root, input);
    const header = [
      "<!--",
      `${TAG}FileCopyrightText: 2025 Kevin de Jong <monkaii@hotmail.com>`,
      `${TAG}FileCopyrightText: 2024 Other Holder`,
      `${TAG}License-Identifier: CC-BY-4.0`,
      "-->",
    ].join("\n");
    expect(read(root, file)).toContain(`question:\n---\n\n${header}\n\n# Decisions are files\n\nWe use files.\n`);
    expect(read(root, "docs/decisions.md")).toMatch(/^<!-- Generated by plan-me [^\n]*-->\n<!--\n/);
    expect(read(root, "docs/decisions.md")).toContain(header);
    const parsed = parseDecision(file, read(root, file));
    expect(parsed.problems).toEqual([]);
    expect(parsed.decision).toMatchObject({ title: "Decisions are files", text: "We use files.", license: header });
    expect(checkDecisions(root)).toEqual([]);
  });

  test("superseding keeps the older file's header; a rule's year and the sole licence file are used", () => {
    const root = repo({
      ".reuse-me.json": JSON.stringify({ rules: [{ paths: ["docs/decisions/"], holder: "Owner", year: 2020 }] }),
      "LICENSES/MIT.txt": "MIT",
    });
    recordDecision(root, { ...input, title: "Old" });
    recordDecision(root, { ...input, supersedes: "old" });
    const old = read(root, "docs/decisions/2025-03-04-old.md");
    expect(old).toContain(`${TAG}FileCopyrightText: 2020 Owner\n${TAG}License-Identifier: MIT\n`);
    expect(old).toContain("status: superseded");
    expect(checkDecisions(root)).toEqual([]);
  });

  test("the import writes the header too; an excluded path or no .reuse-me.json writes none", () => {
    const list = "- **L1** (2026-10-16) A learning game for the son.\n";
    const withConfig = repo({ ".reuse-me.json": REUSE, "list.md": list });
    importDecisions(withConfig, "list.md", "labelled");
    expect(read(withConfig, "docs/decisions/2026-10-16-a-learning-game-for-the-son.md")).toContain(
      `${TAG}License-Identifier: CC-BY-4.0`
    );
    const excluded = repo({
      ".reuse-me.json": JSON.stringify({ ...JSON.parse(REUSE), exclude: ["docs/**"] }),
      "list.md": list,
    });
    importDecisions(excluded, "list.md", "labelled");
    expect(read(excluded, "docs/decisions/2026-10-16-a-learning-game-for-the-son.md")).not.toContain(TAG);
    const without = repo({ "list.md": list });
    importDecisions(without, "list.md", "labelled");
    expect(read(without, "docs/decisions/2026-10-16-a-learning-game-for-the-son.md")).not.toContain(TAG);
    expect(read(without, "docs/decisions.md")).not.toContain(TAG);
  });
});
